export async function encodeFixture(value = fixture) {
  const table = new LayerTable();
  return joinBytes([
    recordingHeader(value.protected, value.created, value.version),
    metaChunk(value.meta),
    ...(value.initial ? [await snapshotChunk(value.initial, table)] : []),
    await eventsChunk(value.events, 0, table),
    endChunk(value.duration, value.events.length),
  ]);
}
